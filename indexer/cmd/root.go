func initConfig() {
	if err := configs.LoadConfig(cfgFile); err != nil {
		log.Fatal().Err(err).Msg("failed to load config")
	}
	customLogger.InitLogger()
}

func bindPFlag(key, flagName string) {
	if err := viper.BindPFlag(key, rootCmd.PersistentFlags().Lookup(flagName)); err != nil {
		log.Fatal().Err(err).Str("flag", flagName).Msg("unable to bind flag")
	}
}
